import { expect, test } from "@playwright/test";

test("guest confirms sharing, retains ownership, and claims content on login", async ({ page, context, browser }, testInfo) => {
  test.setTimeout(120_000);
  const title = `浏览器内容 ${Date.now()}`;
  let creations = 0;
  page.on("request", request => { if (request.method() === "POST" && new URL(request.url()).pathname === "/api/v1/pastes") creations++; });
  await page.goto("/");
  await page.locator(".cm-content").fill("Guest ownership stays in this browser.");
  await page.getByLabel("标题", { exact: true }).fill(title);
  await page.getByRole("button", { name: "生成分享链接", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog).toBeVisible();
  expect(creations).toBe(0);
  await dialog.getByLabel("有效期", { exact: true }).click();
  await page.getByRole("option", { name: "1 小时", exact: true }).click();
  await dialog.getByLabel("访问密码", { exact: true }).fill("browser-test-pass");
  await page.screenshot({ path: testInfo.outputPath("share-confirm-dark.png"), fullPage: true });
  await page.keyboard.press("Escape");
  await expect(dialog).toBeHidden();
  expect(creations).toBe(0);
  await page.getByRole("button", { name: "生成分享链接", exact: true }).click();
  await expect(dialog.getByLabel("有效期", { exact: true })).toContainText("1 小时");
  const responsePromise = page.waitForResponse(response => response.request().method() === "POST" && new URL(response.url()).pathname === "/api/v1/pastes");
  await dialog.getByRole("button", { name: "生成分享链接", exact: true }).click();
  const response = await responsePromise;
  expect(response.status()).toBe(201);
  const value = (await response.json()).paste;
  expect(new Date(value.expiresAt).getTime() - new Date(value.createdAt).getTime()).toBeGreaterThan(3_590_000);
  expect(new Date(value.expiresAt).getTime() - new Date(value.createdAt).getTime()).toBeLessThanOrEqual(3_600_000);
  expect(creations).toBe(1);
  await expect(page.getByRole("button", { name: "删除此链接" })).toBeVisible();
  const origin = new URL(page.url()).origin;
  const cookies = await context.cookies();
  const guestCookie = cookies.find(cookie => cookie.name.endsWith("yueli_guest"));
  expect(guestCookie?.httpOnly).toBe(true);
  expect(guestCookie?.expires).toBeGreaterThan(Date.now() / 1000 + 86400);
  await page.reload();
  await expect(page.getByRole("button", { name: "删除此链接" })).toBeVisible();
  await expect(page.locator(".cm-content")).toContainText("Guest ownership");
  const outsider = await browser.newContext();
  try {
    const other = await outsider.newPage();
    await other.goto(`${origin}/p/${value.code}`);
    await expect(other.getByRole("heading", { name: "需要访问密码" })).toBeVisible();
    expect((await other.request.get(`${origin}/api/v1/me/pastes/${value.code}`)).status()).toBe(401);
    expect([401, 403]).toContain((await other.request.delete(`${origin}/api/v1/me/pastes/${value.code}?expectedRevision=1`)).status());
  } finally { await outsider.close(); }
  await page.getByRole("link", { name: "编辑此内容" }).click();
  await expect(page.getByLabel("标题", { exact: true })).toHaveValue(title);
  await page.getByLabel("标题", { exact: true }).fill(`${title} 已编辑`);
  await page.getByRole("button", { name: "保存修改", exact: true }).click();
  await expect(page.getByRole("heading", { name: `${title} 已编辑`, exact: true })).toBeVisible();
  await page.goto("/mine");
  await expect(page.locator(".paste-ledger-row")).toHaveCount(1);
  await expect(page.getByText("当前浏览器", { exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("guest-library-dark.png"), fullPage: true });
  await page.evaluate(() => localStorage.setItem("nuxt-color-mode", "light"));
  await page.reload();
  await expect(page.locator(".paste-ledger-row")).toHaveCount(1);
  await page.screenshot({ path: testInfo.outputPath("guest-library-light.png"), fullPage: true });
  await page.goto("/auth/login?return_to=%2Fmine");
  await page.getByLabel("邮箱").waitFor();
  await page.waitForFunction(() => Boolean((document.querySelector('form input[name="email"]')?.closest("form") as HTMLFormElement & { __vueParentComponent?: unknown })?.__vueParentComponent));
  await page.getByLabel("邮箱").fill(process.env.PASTE_E2E_EMAIL || "test@example.com");
  await page.getByLabel("密码", { exact: true }).fill(process.env.PASTE_E2E_PASSWORD || "Yueli-local-development-2026");
  await page.getByRole("button", { name: "登录", exact: true }).click();
  await page.waitForURL(/\/mine(?:\?|$)/);
  await expect(page.getByRole("button", { name: /打开.+的用户菜单/ })).toBeVisible();
  await expect.poll(async () => (await page.request.get(`/api/v1/me/pastes/${value.code}`)).status()).toBe(200);
  await expect.poll(async () => (await context.cookies(origin)).some(cookie => cookie.name.endsWith("yueli_guest"))).toBe(false);
  await page.goto(`/p/${value.code}`);
  await expect(page.getByRole("button", { name: "删除此链接" })).toBeVisible();
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "删除此链接" }).click();
  await expect(page).toHaveURL(/\/mine$/);
  expect((await page.request.get(`/api/v1/pastes/${value.code}`)).status()).toBe(410);
});

test("guest can delete without logging in and clearing cookies removes management", async ({ page, context }) => {
  await page.goto("/mine");
  await expect(page.getByText("内容库还是空的", { exact: true })).toBeVisible();
  const response = await page.request.post("/api/v1/pastes", { data: { files: [{ path: "local.txt", content: "local delete" }] } });
  expect(response.status()).toBe(201);
  const { paste } = await response.json();
  const ownerCookies = await context.cookies();
  await context.clearCookies();
  expect((await page.request.get(`/api/v1/me/pastes/${paste.code}`)).status()).toBe(401);
  await context.addCookies(ownerCookies);
  await page.goto(`/p/${paste.code}`);
  await expect(page.getByRole("button", { name: "删除此链接" })).toBeVisible();
  page.once("dialog", dialog => dialog.dismiss());
  await page.getByRole("button", { name: "删除此链接" }).click();
  await expect(page.getByRole("button", { name: "删除此链接" })).toBeVisible();
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "删除此链接" }).click();
  await expect(page).toHaveURL(/\/mine$/);
  await expect(page.getByText("内容库还是空的", { exact: true })).toBeVisible();
});
